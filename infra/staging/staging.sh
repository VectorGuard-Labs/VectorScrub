#!/usr/bin/env bash
# A staging deployment built the way production is: the same compose file, the same three images
# built from this checkout, a real PyHSM image built from a pinned PyHSM commit, ENVIRONMENT=production
# (so every production check in the backend applies), and its own freshly generated secrets.
#
#   infra/staging/staging.sh up        build, start, create the key, wait until healthy
#   infra/staging/staging.sh smoke     the checks in docs/security/PENTEST_BRIEF.md that a script can make
#   infra/staging/staging.sh backup    run the PRODUCTION backup scripts (database and keystore) against
#                                      staging, encrypted to staging-only GPG keys, copied to the
#                                      off-site store (S3, or a local S3-compatible stand-in)
#   infra/staging/staging.sh drill     restore BOTH from the off-site store and prove the data opens
#   infra/staging/staging.sh status
#   infra/staging/staging.sh down      stop; keep volumes (keystore, database)
#   infra/staging/staging.sh destroy   stop and DELETE the volumes and the secrets (asks first)
#
# Run it on a machine that is NOT production. The compose file uses fixed container names, so it
# cannot share a host with a production stack, and staging must never hold real customer data:
# register fake identities only.
#
# Settings (environment):
#   PYHSM_SRC      path to a checkout of the PyHSM repository (required for `up`)
#   PYHSM_REF      the tag or commit that checkout must be at (default v2.4.0). The script refuses
#                  to build from anything else, so the image is the one you meant to run.
#   STAGING_DIR    where the secrets live (default ~/.vectorscrub-staging, mode 700)
#   STAGING_S3_URI where backups go (default: a local S3-compatible stand-in, moto, on 127.0.0.1:9900,
#                  bucket "vectorscrub-staging-backups"; in memory and not off-site). Set it, with AWS credentials in the
#                  environment, to use a real bucket made by infra/backup/aws-offsite-setup.sh.
#   STAGING_URL    what `smoke` talks to (default http://127.0.0.1:3000, the web app, which proxies
#                  /api/v1 to the backend as the reverse proxy does in production). On a real
#                  staging host use its https:// address.
set -euo pipefail
umask 077

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo="$(cd "$here/../.." && pwd)"
compose_dir="$repo/infra/docker"
STAGING_DIR="${STAGING_DIR:-$HOME/.vectorscrub-staging}"
PROJECT=vsstaging
ENV_FILE="$STAGING_DIR/staging.env"

die() { echo "staging: $*" >&2; exit 1; }
dc() { (cd "$compose_dir" && docker compose -p "$PROJECT" --env-file "$ENV_FILE" "$@"); }
need() { command -v "$1" >/dev/null || die "$1 is required"; }

make_env() {
  [[ -f "$ENV_FILE" ]] && { echo "staging: keeping the secrets in $ENV_FILE"; return; }
  mkdir -p "$STAGING_DIR"; chmod 700 "$STAGING_DIR"
  # Hex for anything that goes into a URL. The keystore password is created once and never replaced:
  # replacing it would lock the keystore.
  openssl rand -base64 36 | tr -d '\n/+=' | cut -c1-40 > "$STAGING_DIR/pyhsm-password"
  chmod 600 "$STAGING_DIR/pyhsm-password"
  cat > "$ENV_FILE" <<ENVEOF
# Generated by staging.sh. Secrets for a STAGING stack only. Mode 600.
COMPOSE_PROJECT_NAME=$PROJECT
POSTGRES_PASSWORD=$(openssl rand -hex 24)
DB_APP_PASSWORD=$(openssl rand -hex 24)
REDIS_PASSWORD=$(openssl rand -hex 24)
JWT_SECRET=$(openssl rand -hex 32)
AGENT_API_KEY=$(openssl rand -hex 32)
PYHSM_IPC_SECRET=$(openssl rand -hex 32)
PYHSM_PASSWORD_FILE=$STAGING_DIR/pyhsm-password
METRICS_TOKEN=$(openssl rand -hex 32)
ENVIRONMENT=production
ALLOWED_ORIGINS=https://staging.example.test
TRUST_PROXY_HEADERS=false
ENVEOF
  chmod 600 "$ENV_FILE"
  echo "staging: wrote $ENV_FILE and the keystore password file"
}

build_pyhsm() {
  [[ -n "${PYHSM_SRC:-}" && -d "$PYHSM_SRC/.git" ]] || die "set PYHSM_SRC to a checkout of the PyHSM repository"
  local want="${PYHSM_REF:-v2.4.0}" have wantsha
  have="$(git -C "$PYHSM_SRC" rev-parse HEAD)"
  wantsha="$(git -C "$PYHSM_SRC" rev-parse "$want^{commit}" 2>/dev/null)" || die "PyHSM has no tag or commit '$want'"
  [[ "$have" == "$wantsha" ]] || die "PyHSM is at ${have:0:12} but $want is ${wantsha:0:12}; check out $want first"
  [[ -z "$(git -C "$PYHSM_SRC" status --porcelain)" ]] || die "the PyHSM checkout has uncommitted changes"
  # The PyHSM build is not reproducible (the same commit gives a new image id each time), and a new
  # id makes compose recreate the key service under a starting backend. So an image is built once
  # per commit and reused; delete the tag to force a rebuild.
  if docker image inspect "pyhsm:staging-${have:0:12}" >/dev/null 2>&1; then
    echo "staging: reusing the PyHSM image already built from ${have:0:12}"
  else
    echo "staging: building PyHSM $want (${have:0:12})..."
    docker build -q -t "pyhsm:staging-${have:0:12}" "$PYHSM_SRC" >/dev/null
  fi
  local id; id="$(docker image inspect "pyhsm:staging-${have:0:12}" --format '{{.Id}}')"
  # Record where the image came from (the table in docs/runbooks/key-service.md).
  printf '%s  PyHSM %s commit %s  image %s\n' "$(date -u +%FT%TZ)" "$want" "$have" "$id" >> "$STAGING_DIR/pyhsm-provenance.log"
  sed -i.bak '/^PYHSM_IMAGE=/d' "$ENV_FILE" && rm -f "$ENV_FILE.bak"
  echo "PYHSM_IMAGE=pyhsm@$id" >> "$ENV_FILE"
  echo "staging: PyHSM image $id (commit ${have:0:12})"
}

cmd_up() {
  need docker; need openssl; need git
  make_env
  build_pyhsm
  # The PyHSM volumes belong to uid 1000 before the first start (docs/runbooks/key-service.md).
  docker volume create "${PROJECT}_pyhsm_data" >/dev/null
  docker volume create "${PROJECT}_pyhsm_socket" >/dev/null
  docker run --rm -v "${PROJECT}_pyhsm_data:/d" -v "${PROJECT}_pyhsm_socket:/s" alpine:3 \
    sh -c 'chown 1000:1000 /d /s && chmod 750 /d && chmod 700 /s'
  dc up -d --build pyhsm postgres redis migrate
  # The key is created once, deliberately by a person (here: by this script on a NEW volume only).
  # `kms status` exits 0 even when the key is missing, so read what it says. A running backend has a
  # fixed address on the agent network, so a second container from `run` cannot start: use `exec`.
  kms() {
    if [[ -n "$(dc ps -q --status running backend 2>/dev/null)" ]]; then
      dc exec -T backend ./vectorscrub kms "$@"
    else
      dc run --rm --no-deps backend kms "$@"
    fi
  }
  if kms status 2>&1 | grep -q "exists: true"; then
    echo "staging: the key service already has its key"
  else
    kms init
  fi
  dc up -d --build --wait --wait-timeout 900
  dc ps
  echo
  echo "staging: up. Next: infra/staging/staging.sh smoke"
  echo "staging: then take a keystore backup NOW (docs/runbooks/key-service.md, step 4) and run the restore drill."
}


# ---- backups and the drill -------------------------------------------------------------------------
GNUPG_DIR="$STAGING_DIR/gnupg"

staging_gpg() {
  # Two staging-only keys, as production has two (database and keystore), in a private keyring.
  # Their private halves live here only because this is staging; in production they are off the host.
  export GNUPGHOME="$GNUPG_DIR"
  [[ -d "$GNUPGHOME" ]] && return
  mkdir -p "$GNUPGHOME"; chmod 700 "$GNUPGHOME"
  gpg --batch --quiet --passphrase '' --quick-generate-key db-backups@staging.invalid default default never
  gpg --batch --quiet --passphrase '' --quick-generate-key keystore-backups@staging.invalid default default never
}

offsite() {
  if [[ -n "${STAGING_S3_URI:-}" ]]; then S3_BASE="${STAGING_S3_URI%/}"; return; fi
  # A local S3-compatible stand-in (moto, `pip install "moto[s3,server]"`), so the real scripts'
  # upload and download paths run. It is NOT off-site, and it keeps everything in memory: stopping it
  # loses the "off-site" copies. Use STAGING_S3_URI with a real bucket for an actual off-site drill.
  command -v moto_server >/dev/null || die "no STAGING_S3_URI and no moto_server: pip install \"moto[s3,server]\", or set STAGING_S3_URI"
  if ! curl -fs -m 2 http://127.0.0.1:9900/ >/dev/null 2>&1; then
    nohup moto_server -H 127.0.0.1 -p 9900 > "$STAGING_DIR/moto.log" 2>&1 &
    echo $! > "$STAGING_DIR/moto.pid"
    for _ in $(seq 1 30); do curl -fs -m 2 http://127.0.0.1:9900/ >/dev/null 2>&1 && break; sleep 1; done
  fi
  export AWS_ACCESS_KEY_ID=staging AWS_SECRET_ACCESS_KEY=staging AWS_DEFAULT_REGION=us-east-1
  export AWS_ENDPOINT_URL=http://127.0.0.1:9900
  aws s3 mb s3://vectorscrub-staging-backups >/dev/null 2>&1 || true
  S3_BASE=s3://vectorscrub-staging-backups
}

# backup.sh is the script the production backup host runs. Staging's Postgres publishes no port, so
# pg_dump and pg_restore are reached through `docker exec` by two small shims; the script itself is
# unchanged.
pg_shims() {
  local d="$STAGING_DIR/pgshim"; mkdir -p "$d"
  cat > "$d/pg_dump" <<'SHIM'
#!/usr/bin/env bash
out=""; args=()
for a in "$@"; do case "$a" in --file=*) out="${a#--file=}";; --dbname=*) ;; *) args+=("$a");; esac; done
docker exec vectorscrub-postgres pg_dump -U vectorscrub -d vectorscrub "${args[@]}" > "$out"
SHIM
  cat > "$d/pg_restore" <<'SHIM'
#!/usr/bin/env bash
# Only `pg_restore --list FILE` is used by backup.sh.
file="${@: -1}"
docker exec -i vectorscrub-postgres pg_restore --list < "$file"
SHIM
  chmod 700 "$d/pg_dump" "$d/pg_restore"
  printf '%s' "$d"
}

cmd_backup() {
  need gpg; need aws
  staging_gpg; offsite
  local shims; shims="$(pg_shims)"
  echo "staging: database backup (infra/scripts/backup.sh)..."
  DATABASE_URL="" PGDATABASE=vectorscrub PG_BIN_DIR="$shims" BACKUP_DIR="$STAGING_DIR/backups/db" \
    BACKUP_GPG_RECIPIENT=db-backups@staging.invalid BACKUP_S3_URI="$S3_BASE/db" \
    "$repo/infra/scripts/backup.sh"
  echo "staging: keystore backup (infra/scripts/backup_keystore.sh)..."
  local ks="$STAGING_DIR/keystore-copy.enc"
  docker run --rm -v "${PROJECT}_pyhsm_data:/data:ro" alpine:3 cat /data/keystore.enc > "$ks"
  PYHSM_KEYSTORE="$ks" KEYSTORE_BACKUP_DIR="$STAGING_DIR/backups/keystore" \
    BACKUP_GPG_RECIPIENT=keystore-backups@staging.invalid BACKUP_S3_URI="$S3_BASE/keystore" \
    "$repo/infra/scripts/backup_keystore.sh"
  rm -f "$ks"
  echo "staging: both backups are in $S3_BASE"
}

cmd_drill() {
  need gpg; need aws
  staging_gpg; offsite
  local image; image="$(sed -n 's/^PYHSM_IMAGE=//p' "$ENV_FILE")"
  PYHSM_IMAGE="$image" DRILL_PYHSM_PASSWORD_FILE="$STAGING_DIR/pyhsm-password" \
    DRILL_S3_DB_URI="$S3_BASE/db" DRILL_S3_KEYSTORE_URI="$S3_BASE/keystore" \
    DRILL_ENVIRONMENT="${DRILL_ENVIRONMENT:-staging ($(uname -s), ${STAGING_S3_URI:+real bucket}${STAGING_S3_URI:-local S3-compatible store})}" \
    "$repo/infra/scripts/restore_drill.sh"
}

cmd_destroy() {
  read -r -p "Delete the staging stack, its volumes and its secrets? Type 'destroy': " ans
  [[ "$ans" == destroy ]] || die "not confirmed"
  dc down -v --remove-orphans || true
  [[ -f "$STAGING_DIR/moto.pid" ]] && kill "$(cat "$STAGING_DIR/moto.pid")" 2>/dev/null || true
  rm -rf "$STAGING_DIR"
  echo "staging: destroyed"
}

case "${1:-}" in
  up) cmd_up ;;
  smoke) [[ -f "$ENV_FILE" ]] || die "run 'up' first"
         STAGING_ENV_FILE="$ENV_FILE" STAGING_PROJECT="$PROJECT" COMPOSE_DIR="$compose_dir" \
         STAGING_URL="${STAGING_URL:-http://127.0.0.1:3000}" "$here/smoke_test.sh" ;;
  backup) cmd_backup ;;
  drill) cmd_drill ;;
  status) dc ps ;;
  down) dc down ;;
  destroy) cmd_destroy ;;
  *) die "usage: staging.sh up | smoke | backup | drill | status | down | destroy" ;;
esac
