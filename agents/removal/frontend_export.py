"""
Exports the opt-out registry to the frontend, so the dashboard's manual opt-out guide shows
the same sites, links and steps the removal agent uses. The registry here is the single
source of truth; `frontend/src/lib/brokers.generated.ts` is generated from it and a test
(tests/test_brokers_generated.py) fails if the committed file is out of date.

Regenerate with, from agents/:   python -m removal.frontend_export
"""
from __future__ import annotations

import json
from pathlib import Path

from discovery.agent import DISCOVERY_SOURCES
from removal.agent import OPT_OUT_REGISTRY

OUTPUT = Path(__file__).resolve().parents[2] / "frontend" / "src" / "lib" / "brokers.generated.ts"

HEADER = (
    "// GENERATED by agents/removal/frontend_export.py from OPT_OUT_REGISTRY. Do not edit by hand:\n"
    "// change the registry and run `python -m removal.frontend_export` from agents/.\n"
    "// Public information only (site names, opt-out links, steps). No customer data.\n"
)


def brokers() -> list[dict]:
    out = []
    for name, p in sorted(OPT_OUT_REGISTRY.items()):
        out.append(
            {
                "name": name,
                "method": p.procedure_type,
                "optOutUrl": p.opt_out_url,
                "optOutEmail": p.opt_out_email,
                "instructions": p.instructions,
                "estimatedDays": p.estimated_days,
                "requiresIdVerification": p.requires_id_verification,
            }
        )
    return out


def scan_sources() -> list[dict]:
    """Which plan scans which source, in discovery order. `tier` is the lowest plan that scans it
    (free, personal or premium); `manual` sources are listed but cannot be searched automatically."""
    return [
        {"name": s["name"], "tier": s["tier"], "manual": bool(s.get("manual"))}
        for s in DISCOVERY_SOURCES
    ]


def render() -> str:
    body = json.dumps(brokers(), indent=2, ensure_ascii=False)
    sources = json.dumps(scan_sources(), indent=2, ensure_ascii=False)
    return (
        HEADER
        + "\nexport interface BrokerOptOut {\n"
        + '  name: string;\n  method: "web_form" | "email";\n  optOutUrl: string | null;\n'
        + "  optOutEmail: string | null;\n  instructions: string;\n  estimatedDays: number;\n"
        + "  requiresIdVerification: boolean;\n}\n\n"
        + f"export const BROKER_OPT_OUTS: BrokerOptOut[] = {body};\n\n"
        + "export interface ScanSource {\n  name: string;\n  tier: \"free\" | \"personal\" | \"premium\";\n  manual: boolean;\n}\n\n"
        + f"export const SCAN_SOURCES: ScanSource[] = {sources};\n"
    )


if __name__ == "__main__":
    OUTPUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUTPUT} ({len(OPT_OUT_REGISTRY)} brokers)")
